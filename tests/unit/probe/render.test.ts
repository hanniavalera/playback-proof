import { describe, expect, it } from 'vitest';
import { PROBE_CASES } from '../../../src/lab/probe/formats.ts';
import { cellText, deriveGaps, renderMatrix, renderSummary } from '../../../src/lab/probe/render.ts';
import { parseResultFile, serializeResultFile } from '../../../src/lab/probe/report.ts';
import { UNSUPPORTED_FAILURE, probedEngine, resultFile, twoEnvironments, verdict } from './fixtures.ts';

describe('cellText', () => {
  it('shows ok, intermittent and fail with their counts', () => {
    expect(cellText(probedEngine(), verdict(5, 5, true))).toBe('ok 5/5');
    expect(cellText(probedEngine(), verdict(1, 3, undefined))).toBe('intermittent 1/3');
    expect(cellText(probedEngine(), verdict(0, 3, undefined))).toBe('fail 0/3');
  });

  it('flags a claim of support that did not decode, loudly (bold), for fail and intermittent alike', () => {
    expect(cellText(probedEngine(), verdict(0, 5, true))).toBe('**fail 0/5 — claims true but fails**');
    expect(cellText(probedEngine(), verdict(2, 5, true))).toBe(
      '**intermittent 2/5 — claims true but fails**',
    );
  });

  it('keeps an honest "no" quiet and notes the opposite disagreement', () => {
    expect(cellText(probedEngine(), verdict(0, 5, false, UNSUPPORTED_FAILURE))).toBe(
      'fail 0/5 (claims false)',
    );
    expect(cellText(probedEngine(), verdict(5, 5, false))).toBe('ok 5/5 — claims false but plays');
  });

  it('distinguishes an engine that did not start from a case that was not run', () => {
    expect(cellText({ launchFailed: 'boom' }, undefined)).toBe('launch failed');
    expect(cellText(probedEngine(), undefined)).toBe('—');
    expect(cellText(undefined, undefined)).toBe('—');
  });
});

describe('renderMatrix', () => {
  const document = renderMatrix(twoEnvironments());

  it('is deterministic and does not depend on the order of the files', () => {
    const [mac, linux] = twoEnvironments();
    expect(renderMatrix([linux!, mac!])).toBe(document);
    expect(renderMatrix(twoEnvironments())).toBe(document);
    expect(document.endsWith('\n')).toBe(true);
  });

  it('starts with the generated-file notice and explains how to read it', () => {
    expect(document).toMatch(
      /^# Codec and MSE capability matrix\n\n> Generated by `npm run codec-matrix -- --render`/,
    );
    expect(document).toContain('## How to read it');
    expect(document).toContain('claims true but fails');
  });

  it('records how each environment was produced: command, date, versions, commit', () => {
    expect(document).toContain('`npm run codec-matrix -- --browsers chromium,firefox,webkit --attempts 5`');
    expect(document).toContain(
      '`npm run docker:pw -- npm run codec-matrix -- --browsers chromium,firefox,webkit --attempts 5`',
    );
    expect(document).toContain('2030-01-02');
    expect(document).toContain('container limited to 4');
    expect(document).toContain('`abc1234`');
    expect(document).toContain('Fixture Linux 24.04');
  });

  it('renders one matrix per environment with the engines as columns and the cases as rows', () => {
    expect(document).toContain('### fixture-linux-arm64: Fixture Linux 24.04, arm64');
    expect(document).toContain('### fixture-mac-arm64: Fixture OS 1.0, arm64');
    expect(document).toContain('| Case | chromium 100.0 | firefox 200.0 | webkit 3.0 |');
    expect(document).toContain('| Case | chromium 100.0 | firefox | webkit 3.0 |');
    for (const probeCase of PROBE_CASES) expect(document).toContain(`\`${probeCase.id}\``);
  });

  it('puts the verdicts of the fixtures into the right cells', () => {
    const row = (id: string, env: string): string => {
      const section = document.split(`### ${env}`)[1] ?? '';
      return section.split('\n').find((line) => line.startsWith(`| \`${id}\``)) ?? '';
    };
    expect(row('cmaf-vp9-aac', 'fixture-linux-arm64')).toMatch(
      /^\| `cmaf-vp9-aac` .* \| ok 5\/5 \| ok 5\/5 \| \*\*intermittent 2\/5 — claims true but fails\*\* \|$/,
    );
    expect(row('hevc-fmp4-video', 'fixture-mac-arm64')).toContain('fail 0/5 (claims false)');
    expect(row('cmaf-vp9-aac', 'fixture-mac-arm64')).toMatch(/\| ok 5\/5 \| launch failed \| ok 5\/5 \|$/);
    expect(row('opus-fmp4-audio', 'fixture-mac-arm64')).toContain('ok 5/5 — claims false but plays');
  });

  it('shows the sensitivity rows, the controls and what each engine claims', () => {
    expect(document).toContain('`unmuted`');
    expect(document).toContain('`prefetch`');
    expect(document).toContain('`native-vp9-fmp4-video`');
    expect(document).toContain('| `video/mp4; codecs="vp09.00.10.08"` | true | true | true |');
    expect(document).toContain('| `video/mp4; codecs="hvc1.1.6.L93.B0"` | false | launch failed | true |');
  });

  it('documents each gap with symptom, evidence and consequence', () => {
    const gaps = document.split('## Documented gaps')[1]?.split('## How the lab chooses a format')[0] ?? '';
    expect(gaps).toContain('### Gap 1: webkit 3.0 on fixture-linux-arm64');
    expect(gaps).toContain('`cmaf-vp9-aac`: intermittent 2/5');
    expect(gaps).toContain('`[play] NotSupportedError: The operation is not supported.`');
    expect(gaps).toContain('`MediaError 4 (MEDIA_ERR_SRC_NOT_SUPPORTED): Failed to push buffer`');
    expect(gaps).toContain('(3 of 5 attempts)');
    expect(gaps).toContain('`isTypeSupported` claims true');
    expect(gaps).toContain('[`fixture-linux-arm64.json`](results/codec-matrix/fixture-linux-arm64.json)');
    expect(gaps).toContain('engines.webkit.cases["cmaf-vp9-aac"]');
    expect(gaps).toContain('Same flavour under other page profiles: `unmuted` ok 5/5, `prefetch` ok 5/5');
    expect(gaps).toContain('all 4 controls ok');
    // The primary flavour is flaky but WebM works: DASH VOD falls back, everything else is skipped, with the reason.
    expect(gaps).toContain('VOD over DASH uses `vod-webm`');
    expect(gaps).toContain('Specs that need VOD over HLS, live over DASH, live over HLS are skipped');
    expect(gaps).toContain('no vod stream plays over hls in webkit 3.0');
  });

  it('documents an engine that does not start with its own error text and where it does run', () => {
    const gaps = document.split('## Documented gaps')[1] ?? '';
    expect(gaps).toContain('### Gap 2: firefox does not start on fixture-mac-arm64');
    expect(gaps).toContain('Could not find profile folder');
    // The document shows the browser's own log; Playwright's repeated call log stays in the JSON only.
    expect(gaps).not.toContain('Call log:');
    expect(gaps).toContain('the whole text is in the JSON');
    expect(gaps).not.toMatch(/ +\n/);
    expect(gaps).toContain('firefox runs the playback suites in `fixture-linux-arm64`');
    expect(gaps).toContain('`engines.firefox.launchFailed`');
  });

  it('lists failures no lab stream depends on separately, without skipping anything for them', () => {
    const other =
      document
        .split('### Other disagreements and failures')[1]
        ?.split('## How the lab chooses a format')[0] ?? '';
    expect(other).toContain('`hevc-fmp4-video`');
    expect(other).toContain('`cmaf-vp9-opus`');
    expect(other).toContain('decoded although `isTypeSupported` said no');
    expect(other).not.toContain('`cmaf-vp9-aac`');
  });

  it('computes the stream choice per environment and engine with the production rule', () => {
    const choice = document.split('## How the lab chooses a format')[1] ?? '';
    expect(choice).toContain(
      '| fixture-linux-arm64 | chromium 100.0 | `vod-cmaf` | `vod-cmaf` | `live-cmaf` | `live-cmaf` |',
    );
    expect(choice).toContain(
      '| fixture-linux-arm64 | webkit 3.0 | `vod-webm` | skipped | skipped | skipped |',
    );
    expect(choice).toContain('| fixture-mac-arm64 | firefox | skipped | skipped | skipped | skipped |');
  });

  it('escapes a pipe in an error text so it cannot break a table row', () => {
    const file = resultFile('fixture-pipe', {
      webkit: probedEngine({
        cases: { 'vp8-webm-video': verdict(0, 5, false, { stage: 'append', error: 'Error: a | b' }) },
      }),
    });
    const text = renderMatrix([file]);
    const row = text.split('\n').find((line) => line.includes('Error: a')) ?? '';
    expect(row).toContain('Error: a \\| b');
    expect(row.replace(/\\\|/g, '').split('|')).toHaveLength(7);
  });

  it('says so when there is nothing to render, instead of failing', () => {
    const empty = renderMatrix([]);
    expect(empty).toContain('No result file is committed yet');
    expect(empty).toContain('No gap in the committed results');
  });

  it('reports a clean result as "no gap"', () => {
    const clean = renderMatrix([
      resultFile('fixture-clean', { chromium: probedEngine(), webkit: probedEngine() }),
    ]);
    expect(clean).toContain('No gap in the committed results');
    expect(clean).toContain('No other case failed or disagreed');
  });

  it('survives a round trip through the committed file format', () => {
    const [mac, linux] = twoEnvironments();
    const reread = [mac!, linux!].map((file) =>
      parseResultFile(serializeResultFile(file), `${file.envId}.json`),
    );
    expect(renderMatrix(reread)).toBe(document);
  });
});

describe('deriveGaps', () => {
  it('finds engines that do not start and lab flavours that are not ok, and nothing else', () => {
    const gaps = deriveGaps(twoEnvironments());
    expect(gaps.map((g) => [g.file.envId, g.engine, g.kind, g.flavours])).toEqual([
      ['fixture-mac-arm64', 'firefox', 'launch', []],
      ['fixture-linux-arm64', 'webkit', 'lab-flavours', ['cmaf-vp9-aac']],
    ]);
  });
});

describe('renderSummary', () => {
  it('prints the same verdicts as plain text for the console, one row per case that was run', () => {
    const [mac] = twoEnvironments();
    const text = renderSummary(mac!);
    expect(text).toContain('fixture-mac-arm64  (5 attempts per case)');
    expect(text).toContain('chromium 100.0');
    expect(text).toMatch(/cmaf-vp9-aac\s+ok 5\/5\s+\|\s+launch failed\s+\|\s+ok 5\/5/);
    expect(text).not.toContain('**');
  });
});
