// The media pipeline as the HTTP service sees it: `createMediaStore` implements the MediaStore interface of ./types.ts over the
// content-addressed cache that `npm run generate:streams` writes. Files are read lazily and kept in memory (the whole catalog is about
// 50 MB), bounded by `maxCacheBytes` with least-recently-used eviction. Live segments are source segments with their decode time moved
// by whole loops (rewriteTfdt); manifests are pure functions of the index (dash.ts, hls.ts).
//
// Construction never throws for a missing or damaged stream: that stream is simply not ready (has() is false, index() explains why).

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { STREAM_IDS, type StreamId, type StreamInfo } from '../../shared/streams.ts';
import {
  checkStreamDir,
  defaultCacheDir,
  initFileName,
  segmentFileName,
  streamDir,
  type StreamFile,
} from './cache.ts';
import { buildDashLive, buildDashVod } from './dash.ts';
import { buildHlsMaster, buildHlsMediaLive, buildHlsMediaVod } from './hls.ts';
import { rewriteTfdt } from './isobmff.ts';
import { assertLiveNumber, liveSource, liveTiming } from './live.ts';
import { CATALOG, type StreamSpec } from './specs.ts';
import type { DashLiveParams, HlsLiveParams, MediaStore, RepIndex, StreamIndex } from './types.ts';

export interface MediaStoreOptions {
  /** Root of the content-addressed stream cache. Default: <repo>/.cache/streams */
  cacheDir?: string;
  /** Upper bound of the files kept in memory, in bytes. Default 256 MiB (the whole catalog is about 50 MB). */
  maxCacheBytes?: number;
  /** The specs whose caches to look for. Default: the catalog. Tests pass tiny specs generated by the real pipeline. */
  specs?: StreamSpec[];
}

interface Ready {
  dir: string;
  file: StreamFile;
}

class FileCache {
  private readonly files = new Map<string, Buffer>();
  private bytes = 0;
  constructor(private readonly maxBytes: number) {}

  read(path: string): Buffer {
    const hit = this.files.get(path);
    if (hit) {
      // Re-insert to mark it most recently used: a Map iterates in insertion order.
      this.files.delete(path);
      this.files.set(path, hit);
      return hit;
    }
    const data = readFileSync(path);
    this.files.set(path, data);
    this.bytes += data.length;
    for (const [key, value] of this.files) {
      if (this.bytes <= this.maxBytes || key === path) break;
      this.files.delete(key);
      this.bytes -= value.length;
    }
    return data;
  }
}

export function createMediaStore(options: MediaStoreOptions = {}): MediaStore {
  const cacheDir = options.cacheDir ?? defaultCacheDir();
  const specs = options.specs ?? CATALOG;
  const cache = new FileCache(options.maxCacheBytes ?? 256 * 1024 * 1024);
  const ready = new Map<StreamId, Ready>();
  const notReady = new Map<StreamId, string>();

  for (const id of STREAM_IDS) {
    const spec = specs.find((s) => s.id === id);
    if (!spec) {
      notReady.set(id, 'not in the catalog (the ClearKey stretch goal is not implemented)');
      continue;
    }
    const dir = streamDir(cacheDir, spec);
    try {
      const check = checkStreamDir(dir, spec, { hash: false });
      if (check.ok && check.file) ready.set(id, { dir, file: check.file });
      else notReady.set(id, `${dir}: ${check.problems.join('; ')}`);
    } catch (e) {
      notReady.set(id, `${dir}: ${(e as Error).message}`);
    }
  }

  const vodManifests = new Map<string, string>();

  const get = (id: StreamId): Ready => {
    const r = ready.get(id);
    if (!r) {
      const why = notReady.get(id) ?? 'unknown stream id';
      throw new Error(`stream '${id}' is not ready: ${why}. Run \`npm run generate:streams\` (idempotent).`);
    }
    return r;
  };
  const indexOf = (id: StreamId): StreamIndex => get(id).file.index;
  const repOf = (id: StreamId, repId: string): RepIndex => {
    const index = indexOf(id);
    const rep = index.reps.find((r) => r.rep.id === repId);
    if (!rep)
      throw new Error(
        `stream '${id}' has no representation '${repId}' (has: ${index.reps.map((r) => r.rep.id).join(', ')})`,
      );
    return rep;
  };
  const requireLive = (id: StreamId): void => {
    if (indexOf(id).info.kind !== 'live') throw new Error(`stream '${id}' is not live`);
  };
  const segmentBuffer = (id: StreamId, rep: RepIndex, number: number): Buffer =>
    cache.read(join(get(id).dir, segmentFileName(rep.rep, number)));
  const memo = (key: string, build: () => string): string => {
    let v = vodManifests.get(key);
    if (v === undefined) {
      v = build();
      vodManifests.set(key, v);
    }
    return v;
  };

  return {
    ffmpegVersion(): string {
      for (const id of STREAM_IDS) {
        const r = ready.get(id);
        if (r) return r.file.ffmpegVersion;
      }
      return 'unknown';
    },
    streams(): StreamInfo[] {
      return STREAM_IDS.filter((id) => ready.has(id)).map((id) => indexOf(id).info);
    },
    has: (id) => ready.has(id),
    index: indexOf,

    init(id, repId) {
      return cache.read(join(get(id).dir, initFileName(repOf(id, repId).rep)));
    },
    segment(id, repId, number) {
      const rep = repOf(id, repId);
      if (!Number.isInteger(number) || number < 1 || number > rep.segments.length) return undefined;
      return segmentBuffer(id, rep, number);
    },
    liveSegment(id, repId, number) {
      requireLive(id);
      const rep = repOf(id, repId);
      assertLiveNumber(number);
      const { source, loop } = liveSource(rep.segments.length, number);
      const loopTicks = loop * rep.loopTicks;
      if (!Number.isSafeInteger(loopTicks))
        throw new RangeError(`live segment ${number} lies beyond 2^53 ticks`);
      // Always a fresh buffer: the source stays untouched in the cache.
      return rewriteTfdt(segmentBuffer(id, rep, source), loopTicks);
    },
    liveSegmentTiming(id, repId, number) {
      requireLive(id);
      return liveTiming(repOf(id, repId), number);
    },

    dashVod: (id) => memo(`dash:${id}`, () => buildDashVod(indexOf(id))),
    dashLive: (id, params: DashLiveParams) => buildDashLive(indexOf(id), params),
    hlsMaster: (id) => memo(`hls:${id}`, () => buildHlsMaster(indexOf(id))),
    hlsMediaVod: (id, repId) => memo(`hls:${id}:${repId}`, () => buildHlsMediaVod(indexOf(id), repId)),
    hlsMediaLive: (id, repId, params: HlsLiveParams) => buildHlsMediaLive(indexOf(id), repId, params),
  };
}
